"""Build the fonts embedded in the PDF report.

jsPDF's built-in fonts cannot draw the rupee sign, so the report embeds small
subsets of Noto Sans / Noto Serif (SIL Open Font License 1.1). Run this only
when the character set or weights change; the generated TypeScript modules are
committed so normal builds need neither fonttools nor the source fonts.

    pip install fonttools
    python scripts/build_report_fonts.py <dir with NotoSans[wdth,wght].ttf and NotoSerif[wdth,wght].ttf>
"""

import base64
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "src" / "lib" / "report" / "fonts"

# Basic Latin, Latin-1, and the specific symbols the report uses.
UNICODES = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + [
        0x2013,  # en dash
        0x2014,  # em dash
        0x2018, 0x2019, 0x201C, 0x201D,  # curly quotes
        0x2022,  # bullet
        0x2026,  # ellipsis
        0x20B9,  # INDIAN RUPEE SIGN
        0x2212,  # minus sign (negative amounts)
        0x00B7,  # middle dot
        0x2192,  # arrow
    ]
)

# (source file, output name, weight, TS export)
FONTS = [
    ("NotoSerif[wdth,wght].ttf", "NotoSerif-Regular", 400, "NOTO_SERIF_REGULAR"),
    ("NotoSans[wdth,wght].ttf", "NotoSans-Regular", 400, "NOTO_SANS_REGULAR"),
    ("NotoSans[wdth,wght].ttf", "NotoSans-Bold", 700, "NOTO_SANS_BOLD"),
]


def build(src: Path, weight: int) -> bytes:
    font = TTFont(src)
    static = instancer.instantiateVariableFont(font, {"wght": weight, "wdth": 100})
    options = subset.Options()
    options.layout_features = ["kern"]
    options.hinting = False
    options.name_IDs = [1, 2, 4, 6]
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(static)
    buffer = io.BytesIO()
    static.save(buffer)
    return buffer.getvalue()


def main(source_dir: str) -> int:
    src_dir = Path(source_dir)
    OUT.mkdir(parents=True, exist_ok=True)
    for source, name, weight, export in FONTS:
        data = build(src_dir / source, weight)
        covered = TTFont(io.BytesIO(data)).getBestCmap()
        assert 0x20B9 in covered, f"{name} is missing the rupee sign"
        assert 0x2212 in covered, f"{name} is missing the minus sign"
        encoded = base64.b64encode(data).decode("ascii")
        (OUT / f"{name}.ts").write_text(
            "// Generated by scripts/build_report_fonts.py. Do not edit.\n"
            f"// {name}: Noto subset, SIL Open Font License 1.1.\n"
            f'export const {export} = "{encoded}";\n',
            encoding="utf-8",
        )
        print(f"{name}: {len(data) / 1024:.1f} KB ({len(encoded) / 1024:.1f} KB base64)")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1]))
